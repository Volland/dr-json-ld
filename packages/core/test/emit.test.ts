const GOLDEN = fileURLToPath(new URL('./fixtures/golden/', import.meta.url))
const DOCUMENTS = fileURLToPath(new URL('./fixtures/documents/', import.meta.url))
const UPDATE = process.env['UPDATE_GOLDEN'] === '1'

const UPSTREAM = 'https://example.org/vocab/core.jsonld'
const UPSTREAM_BODY = {
  '@context': {
    schema: 'https://schema.org/',
    name: 'schema:name',
    homepage: { '@id': 'schema:url', '@type': '@id' },
  },
}

const dirs: string[] = []
afterEach(() => {
  while (dirs.length) rmSync(dirs.pop()!, { recursive: true, force: true })
})

function resolveContext(iri: string): unknown {
  return iri === UPSTREAM ? UPSTREAM_BODY : undefined
}

function build(text: string, path = 'model.jsonld.yaml') {
  const source = SourceIndex.parse(text, { path })
  const { ir, findings } = resolveModelText(text, path)
  return { ir: ir!, source, resolveFindings: findings }
}

/** A golden file detects unintended churn; it never proves correctness. */
function golden(name: string, actual: string): void {
  const path = join(GOLDEN, name)
  if (UPDATE || !existsSync(path)) {
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, actual)
    return
  }
  expect(actual, `golden ${name} — rerun with UPDATE_GOLDEN=1 if intended`).toBe(
    readFileSync(path, 'utf8'),
  )
}

